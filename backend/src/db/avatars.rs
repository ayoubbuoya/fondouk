//! Queries for the characters tables: `users`, `avatar_configs` and `avatars`.
//!
//! Enum-like columns (`risk`, `goal`, `mode`) are plain strings here, like
//! `villages.kind`; the database CHECK constraints reject unknown values.

use chrono::{DateTime, Utc};
use rust_decimal::Decimal;
use sqlx::{PgExecutor, PgPool};
use uuid::Uuid;

/// Input for a new strategy (`avatar_configs` row). Rows are never updated (Q-B).
#[derive(Debug, Clone)]
pub struct NewConfig {
    /// Private strategy text, 1 to 2000 characters (Q-A).
    pub persona: String,
    /// `low`, `medium` or `high`.
    pub risk: String,
    /// `steady_income`, `max_yield` or `protect_capital`.
    pub goal: String,
    pub created_by: String,
}

/// Input for a new character. It starts with all its capital in cash (Q-E).
#[derive(Debug, Clone)]
pub struct NewAvatar {
    pub owner: String,
    pub config_id: Uuid,
    pub name: String,
    pub sprite: String,
    /// `sim` or `real`.
    pub mode: String,
    pub starting_capital_usd: Decimal,
    /// `false` = paused: the tick loop skips it until the owner starts it.
    /// A create from the UI starts paused, so the owner reads the backtest
    /// first (D63).
    pub active: bool,
}

/// A character together with the strategy it runs.
///
/// **Contains the private `persona`.** Use it inside the backend (backtest,
/// agent); never send it as-is to a client other than the owner.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct AvatarWithConfig {
    pub id: Uuid,
    pub owner: String,
    pub name: String,
    pub sprite: String,
    pub mode: String,
    pub starting_capital_usd: Decimal,
    pub cash_usd: Decimal,
    pub active: bool,
    pub cloned_from: Option<Uuid>,
    pub listed: bool,
    pub created_at: DateTime<Utc>,
    pub config_id: Uuid,
    pub persona: String,
    pub risk: String,
    pub goal: String,
    /// Who wrote the strategy (`avatar_configs.created_by`). Only this account
    /// may read the persona (D39); for a clone it is the creator, not the buyer.
    pub config_created_by: String,
}

/// The fields `PATCH /avatars/:id` may change (D40). The caller passes the
/// full new values (old value for anything not being changed).
#[derive(Debug, Clone)]
pub struct AvatarUpdate {
    pub name: String,
    pub sprite: String,
    pub active: bool,
    /// A new strategy row when the persona changed, else the current one.
    pub config_id: Uuid,
}

/// Creates the user if it does not exist yet. Calling it again is a no-op.
pub async fn ensure_user<'e>(executor: impl PgExecutor<'e>, account_id: &str) -> sqlx::Result<()> {
    sqlx::query!(
        "INSERT INTO users (account_id) VALUES ($1) ON CONFLICT (account_id) DO NOTHING",
        account_id,
    )
    .execute(executor)
    .await?;
    Ok(())
}

/// Locks `account_id`'s user row until the transaction ends, then counts the
/// avatars it owns (clones included). Used for the per-account limit (D63).
///
/// The lock is what makes the limit safe: two creates sent at the same time
/// by the same account wait for each other here, so the second one counts
/// the first one's avatar instead of both seeing the old count.
pub async fn lock_owner_and_count_avatars(
    conn: &mut sqlx::PgConnection,
    account_id: &str,
) -> sqlx::Result<i64> {
    sqlx::query!(
        "SELECT account_id FROM users WHERE account_id = $1 FOR UPDATE",
        account_id,
    )
    .fetch_optional(&mut *conn)
    .await?;
    let count = sqlx::query_scalar!(
        r#"SELECT COUNT(*) AS "count!" FROM avatars WHERE owner = $1"#,
        account_id,
    )
    .fetch_one(&mut *conn)
    .await?;
    Ok(count)
}

/// Stores a new strategy and returns its id (generated by Postgres).
///
/// # Errors
/// Foreign key violation if `created_by` is not a user; CHECK violation for a
/// persona outside 1..=2000 characters or an unknown `risk` / `goal`.
pub async fn insert_config<'e>(
    executor: impl PgExecutor<'e>,
    config: &NewConfig,
) -> sqlx::Result<Uuid> {
    sqlx::query_scalar!(
        r#"
        INSERT INTO avatar_configs (persona, risk, goal, created_by)
        VALUES ($1, $2, $3, $4)
        RETURNING id
        "#,
        config.persona,
        config.risk,
        config.goal,
        config.created_by,
    )
    .fetch_one(executor)
    .await
}

/// Stores a new character and returns its id. All starting capital goes to
/// `cash_usd`; its first decision allocates it to villages (Q-E).
///
/// # Errors
/// Foreign key violation for an unknown owner or config; CHECK violation for a
/// name outside 1..=32 characters, an unknown `mode`, or capital <= 0.
pub async fn insert_avatar<'e>(
    executor: impl PgExecutor<'e>,
    avatar: &NewAvatar,
) -> sqlx::Result<Uuid> {
    sqlx::query_scalar!(
        r#"
        INSERT INTO avatars (owner, config_id, name, sprite, mode, starting_capital_usd, cash_usd, active)
        VALUES ($1, $2, $3, $4, $5, $6, $6, $7)
        RETURNING id
        "#,
        avatar.owner,
        avatar.config_id,
        avatar.name,
        avatar.sprite,
        avatar.mode,
        avatar.starting_capital_usd,
        avatar.active,
    )
    .fetch_one(executor)
    .await
}

/// Input for a clone of a listed character (F11.3, F11.4).
#[derive(Debug, Clone)]
pub struct NewClone {
    pub owner: String,
    /// The character that was bought. The clone points to its strategy row
    /// (`config_id`) and never copies the persona text.
    pub source_id: Uuid,
    pub config_id: Uuid,
    pub name: String,
    pub sprite: String,
    pub starting_capital_usd: Decimal,
}

/// Stores a clone: a sim character with all its capital in cash, pointing to
/// the source's strategy. `listed` stays `false` (F11.5: a clone cannot be
/// re-listed; the table CHECK repeats it).
///
/// # Errors
/// Foreign key violation for an unknown owner, source or config; CHECK
/// violation for a name outside 1..=32 characters or capital <= 0.
pub async fn insert_clone<'e>(
    executor: impl PgExecutor<'e>,
    clone: &NewClone,
) -> sqlx::Result<Uuid> {
    sqlx::query_scalar!(
        r#"
        INSERT INTO avatars
            (owner, config_id, name, sprite, mode, starting_capital_usd, cash_usd, cloned_from)
        VALUES ($1, $2, $3, $4, 'sim', $5, $5, $6)
        RETURNING id
        "#,
        clone.owner,
        clone.config_id,
        clone.name,
        clone.sprite,
        clone.starting_capital_usd,
        clone.source_id,
    )
    .fetch_one(executor)
    .await
}

/// Sets the avatar's cash (live sim, after a tick changed its ledger).
///
/// Takes any executor, so the live tick can run it inside its transaction.
///
/// # Errors
/// CHECK violation for a negative amount; `sqlx::Error::RowNotFound` when no
/// avatar has this id.
pub async fn update_cash<'e>(
    executor: impl PgExecutor<'e>,
    avatar_id: Uuid,
    cash_usd: Decimal,
) -> sqlx::Result<()> {
    let result = sqlx::query!(
        "UPDATE avatars SET cash_usd = $2 WHERE id = $1",
        avatar_id,
        cash_usd,
    )
    .execute(executor)
    .await?;
    if result.rows_affected() == 0 {
        return Err(sqlx::Error::RowNotFound);
    }
    Ok(())
}

/// Loads a character and its strategy, or `None` when the id is unknown.
pub async fn get_avatar_with_config(
    pool: &PgPool,
    id: Uuid,
) -> sqlx::Result<Option<AvatarWithConfig>> {
    sqlx::query_as!(
        AvatarWithConfig,
        r#"
        SELECT a.id, a.owner, a.name, a.sprite, a.mode, a.starting_capital_usd, a.cash_usd,
               a.active, a.cloned_from, a.listed, a.created_at,
               c.id AS config_id, c.persona, c.risk, c.goal,
               c.created_by AS config_created_by
        FROM avatars a
        JOIN avatar_configs c ON c.id = a.config_id
        WHERE a.id = $1
        "#,
        id,
    )
    .fetch_optional(pool)
    .await
}

/// Every avatar (active or not), oldest first; only `owner`'s when given.
/// Used by `GET /avatars`. Contains the persona: the API drops it.
pub async fn list_avatars(
    pool: &PgPool,
    owner: Option<&str>,
) -> sqlx::Result<Vec<AvatarWithConfig>> {
    // `$1 IS NULL OR …` keeps one query for both cases. Fine at hackathon
    // scale (tens of avatars); a large table would want two queries.
    sqlx::query_as!(
        AvatarWithConfig,
        r#"
        SELECT a.id, a.owner, a.name, a.sprite, a.mode, a.starting_capital_usd, a.cash_usd,
               a.active, a.cloned_from, a.listed, a.created_at,
               c.id AS config_id, c.persona, c.risk, c.goal,
               c.created_by AS config_created_by
        FROM avatars a
        JOIN avatar_configs c ON c.id = a.config_id
        WHERE $1::TEXT IS NULL OR a.owner = $1
        ORDER BY a.created_at, a.id
        "#,
        owner,
    )
    .fetch_all(pool)
    .await
}

/// Writes the editable fields of an avatar (D40). Does not touch `cash_usd`,
/// so it cannot overwrite what a tick running at the same time stores.
///
/// # Errors
/// CHECK violation for a name outside 1..=32 characters; foreign key
/// violation for an unknown config; `sqlx::Error::RowNotFound` when no avatar
/// has this id.
pub async fn update_avatar<'e>(
    executor: impl PgExecutor<'e>,
    avatar_id: Uuid,
    update: &AvatarUpdate,
) -> sqlx::Result<()> {
    let result = sqlx::query!(
        "UPDATE avatars SET name = $2, sprite = $3, active = $4, config_id = $5 WHERE id = $1",
        avatar_id,
        update.name,
        update.sprite,
        update.active,
        update.config_id,
    )
    .execute(executor)
    .await?;
    if result.rows_affected() == 0 {
        return Err(sqlx::Error::RowNotFound);
    }
    Ok(())
}

/// Every active avatar in `mode`, with its strategy, oldest first. Used by
/// the agent tick loop.
pub async fn list_active_avatars(pool: &PgPool, mode: &str) -> sqlx::Result<Vec<AvatarWithConfig>> {
    sqlx::query_as!(
        AvatarWithConfig,
        r#"
        SELECT a.id, a.owner, a.name, a.sprite, a.mode, a.starting_capital_usd, a.cash_usd,
               a.active, a.cloned_from, a.listed, a.created_at,
               c.id AS config_id, c.persona, c.risk, c.goal,
               c.created_by AS config_created_by
        FROM avatars a
        JOIN avatar_configs c ON c.id = a.config_id
        WHERE a.active AND a.mode = $1
        ORDER BY a.created_at, a.id
        "#,
        mode,
    )
    .fetch_all(pool)
    .await
}

#[cfg(test)]
mod tests {
    use super::*;

    const OWNER: &str = "alice.testnet";

    fn new_config(persona: &str, risk: &str) -> NewConfig {
        NewConfig {
            persona: persona.to_string(),
            risk: risk.to_string(),
            goal: "steady_income".to_string(),
            created_by: OWNER.to_string(),
        }
    }

    fn new_avatar(config_id: Uuid, capital: i64) -> NewAvatar {
        NewAvatar {
            owner: OWNER.to_string(),
            config_id,
            name: "Hanna".to_string(),
            sprite: "merchant_1".to_string(),
            mode: "sim".to_string(),
            starting_capital_usd: Decimal::from(capital),
            active: true,
        }
    }

    /// User + config, ready for avatars.
    async fn setup_config(pool: &PgPool) -> Uuid {
        ensure_user(pool, OWNER).await.unwrap();
        insert_config(
            pool,
            &new_config("Prefer lending, avoid tiny pools.", "low"),
        )
        .await
        .unwrap()
    }

    fn is_check_violation(err: &sqlx::Error) -> bool {
        err.as_database_error()
            .is_some_and(|db_err| db_err.is_check_violation())
    }

    #[sqlx::test]
    async fn created_avatar_is_read_back_with_its_config(pool: PgPool) {
        let config_id = setup_config(&pool).await;

        let id = insert_avatar(&pool, &new_avatar(config_id, 10_000))
            .await
            .unwrap();
        let avatar = get_avatar_with_config(&pool, id).await.unwrap().unwrap();

        assert_eq!(avatar.id, id);
        assert_eq!(avatar.owner, OWNER);
        assert_eq!(avatar.config_id, config_id);
        assert_eq!(avatar.persona, "Prefer lending, avoid tiny pools.");
        assert_eq!(avatar.risk, "low");
        assert_eq!(avatar.mode, "sim");
        assert!(avatar.active);
        assert!(!avatar.listed);
        assert_eq!(avatar.cloned_from, None);
    }

    #[sqlx::test]
    async fn new_avatar_starts_with_all_capital_in_cash(pool: PgPool) {
        let config_id = setup_config(&pool).await;

        let id = insert_avatar(&pool, &new_avatar(config_id, 10_000))
            .await
            .unwrap();
        let avatar = get_avatar_with_config(&pool, id).await.unwrap().unwrap();

        assert_eq!(avatar.starting_capital_usd, Decimal::from(10_000));
        assert_eq!(avatar.cash_usd, Decimal::from(10_000));
    }

    #[sqlx::test]
    async fn unknown_avatar_id_returns_none(pool: PgPool) {
        let avatar = get_avatar_with_config(&pool, Uuid::nil()).await.unwrap();
        assert_eq!(avatar, None);
    }

    #[sqlx::test]
    async fn ensure_user_twice_is_not_an_error(pool: PgPool) {
        ensure_user(&pool, OWNER).await.unwrap();
        ensure_user(&pool, OWNER).await.unwrap();
    }

    #[sqlx::test]
    async fn persona_longer_than_2000_chars_is_rejected(pool: PgPool) {
        ensure_user(&pool, OWNER).await.unwrap();
        let too_long = "a".repeat(2001);

        let err = insert_config(&pool, &new_config(&too_long, "low"))
            .await
            .unwrap_err();

        assert!(is_check_violation(&err), "{err}");
    }

    #[sqlx::test]
    async fn persona_of_exactly_2000_chars_is_accepted(pool: PgPool) {
        ensure_user(&pool, OWNER).await.unwrap();
        // Multi-byte characters: the limit counts characters, not bytes.
        let max = "é".repeat(2000);

        insert_config(&pool, &new_config(&max, "low"))
            .await
            .unwrap();
    }

    #[sqlx::test]
    async fn unknown_risk_is_rejected(pool: PgPool) {
        ensure_user(&pool, OWNER).await.unwrap();

        let err = insert_config(&pool, &new_config("x", "yolo"))
            .await
            .unwrap_err();

        assert!(is_check_violation(&err), "{err}");
    }

    #[sqlx::test]
    async fn config_for_unknown_user_is_rejected(pool: PgPool) {
        let err = insert_config(&pool, &new_config("x", "low"))
            .await
            .unwrap_err();

        let db_err = err.as_database_error().expect("expected a database error");
        assert!(db_err.is_foreign_key_violation());
    }

    #[sqlx::test]
    async fn zero_starting_capital_is_rejected(pool: PgPool) {
        let config_id = setup_config(&pool).await;

        let err = insert_avatar(&pool, &new_avatar(config_id, 0))
            .await
            .unwrap_err();

        assert!(is_check_violation(&err), "{err}");
    }

    #[sqlx::test]
    async fn a_clone_cannot_be_listed(pool: PgPool) {
        let config_id = setup_config(&pool).await;
        let source = insert_avatar(&pool, &new_avatar(config_id, 1_000))
            .await
            .unwrap();
        let clone = insert_avatar(&pool, &new_avatar(config_id, 1_000))
            .await
            .unwrap();

        // Clone creation is Day 9, so the row is shaped with raw SQL here.
        let err = sqlx::query!(
            "UPDATE avatars SET cloned_from = $1, listed = true, price_yocto = 1 WHERE id = $2",
            source,
            clone,
        )
        .execute(&pool)
        .await
        .unwrap_err();

        assert!(is_check_violation(&err), "{err}");
    }

    #[sqlx::test]
    async fn update_cash_sets_the_cash_and_refuses_negative_amounts(pool: PgPool) {
        let config_id = setup_config(&pool).await;
        let avatar = insert_avatar(&pool, &new_avatar(config_id, 1_000))
            .await
            .unwrap();

        update_cash(&pool, avatar, Decimal::ZERO).await.unwrap();
        let err = update_cash(&pool, avatar, Decimal::NEGATIVE_ONE)
            .await
            .unwrap_err();

        let stored = get_avatar_with_config(&pool, avatar)
            .await
            .unwrap()
            .unwrap();
        assert_eq!(stored.cash_usd, Decimal::ZERO);
        assert!(is_check_violation(&err), "{err}");
        assert!(matches!(
            update_cash(&pool, Uuid::nil(), Decimal::ONE).await,
            Err(sqlx::Error::RowNotFound)
        ));
    }

    #[sqlx::test]
    async fn list_avatars_filters_by_owner(pool: PgPool) {
        let config_id = setup_config(&pool).await;
        insert_avatar(&pool, &new_avatar(config_id, 1_000))
            .await
            .unwrap();
        ensure_user(&pool, "bob.testnet").await.unwrap();
        let bob_config = insert_config(
            &pool,
            &NewConfig {
                created_by: "bob.testnet".to_string(),
                ..new_config("Bob's plan.", "high")
            },
        )
        .await
        .unwrap();
        insert_avatar(
            &pool,
            &NewAvatar {
                owner: "bob.testnet".to_string(),
                ..new_avatar(bob_config, 1_000)
            },
        )
        .await
        .unwrap();

        assert_eq!(list_avatars(&pool, None).await.unwrap().len(), 2);
        let bobs = list_avatars(&pool, Some("bob.testnet")).await.unwrap();
        assert_eq!(bobs.len(), 1);
        assert_eq!(bobs[0].config_created_by, "bob.testnet");
    }

    #[sqlx::test]
    async fn update_avatar_changes_the_editable_fields_only(pool: PgPool) {
        let config_id = setup_config(&pool).await;
        let avatar = insert_avatar(&pool, &new_avatar(config_id, 1_000))
            .await
            .unwrap();
        let new_config_id = insert_config(&pool, &new_config("New plan.", "low"))
            .await
            .unwrap();

        update_avatar(
            &pool,
            avatar,
            &AvatarUpdate {
                name: "Yusra".to_string(),
                sprite: "trader_2".to_string(),
                active: false,
                config_id: new_config_id,
            },
        )
        .await
        .unwrap();

        let stored = get_avatar_with_config(&pool, avatar)
            .await
            .unwrap()
            .unwrap();
        assert_eq!(stored.name, "Yusra");
        assert_eq!(stored.sprite, "trader_2");
        assert!(!stored.active);
        assert_eq!(stored.persona, "New plan.");
        assert_eq!(stored.cash_usd, Decimal::from(1_000), "cash untouched");
        assert!(matches!(
            update_avatar(
                &pool,
                Uuid::nil(),
                &AvatarUpdate {
                    name: "x".to_string(),
                    sprite: "x".to_string(),
                    active: true,
                    config_id,
                }
            )
            .await,
            Err(sqlx::Error::RowNotFound)
        ));
    }
}
